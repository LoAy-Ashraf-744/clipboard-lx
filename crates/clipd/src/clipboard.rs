use std::env;
use std::fs::{self, OpenOptions};
use std::io::{Read, Write};
use std::os::unix::fs::OpenOptionsExt;
use std::path::{Path, PathBuf};
use std::process::{Child, Command, Stdio};
use std::time::{Duration, Instant, SystemTime};

use clip_core::model::{compute_content_hash, parse_png_dimensions, ClipboardEntry, EntryKind};
use clip_core::paths::current_uid;
use clip_core::store::MAX_IMAGE_BYTES;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CapturedClipboard {
    Text(String),
    Image(Vec<u8>),
}

const PRIVACY_TARGETS: &[&str] = &[
    "x-kde-passwordmanagerhint",
    "org.nspasteboard.concealedtype",
    "org.nspasteboard.autogeneratedtype",
    "x-clipd-ignore",
];

fn has_wayland() -> bool {
    env::var("WAYLAND_DISPLAY")
        .map(|v| !v.is_empty())
        .unwrap_or(false)
}

fn has_x11() -> bool {
    env::var("DISPLAY").map(|v| !v.is_empty()).unwrap_or(false)
}

fn newest_mutter_xauth(dir: &Path) -> Option<PathBuf> {
    let entries = fs::read_dir(dir).ok()?;
    let mut best: Option<(SystemTime, PathBuf)> = None;
    for entry in entries.flatten() {
        let name = entry.file_name();
        let name_str = name.to_string_lossy();
        if !name_str.starts_with(".mutter-Xwaylandauth.") {
            continue;
        }
        let path = entry.path();
        let Ok(meta) = entry.metadata() else {
            continue;
        };
        if !meta.is_file() {
            continue;
        }
        let mtime = meta.modified().unwrap_or(SystemTime::UNIX_EPOCH);
        let replace = match &best {
            None => true,
            Some((best_time, _)) => mtime >= *best_time,
        };
        if replace {
            best = Some((mtime, path));
        }
    }
    best.map(|(_, p)| p)
}

/// Resolves a valid `XAUTHORITY` cookie file for X11/XWayland connections.
pub fn resolve_xauthority() -> Option<PathBuf> {
    if let Some(p) = env::var_os("XAUTHORITY") {
        let path = PathBuf::from(p);
        if path.is_file() {
            return Some(path);
        }
    }

    let runtime_dir = env::var_os("XDG_RUNTIME_DIR")
        .filter(|v| !v.is_empty())
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(format!("/run/user/{}", current_uid())));
    if let Some(mutter) = newest_mutter_xauth(&runtime_dir) {
        return Some(mutter);
    }

    if let Some(home) = env::var_os("HOME") {
        let fallback = PathBuf::from(home).join(".Xauthority");
        if fallback.is_file() {
            return Some(fallback);
        }
    }

    None
}

fn apply_xclip_env(cmd: &mut Command, program: &str) {
    if program == "xclip" {
        if let Some(xauth) = resolve_xauthority() {
            cmd.env("XAUTHORITY", xauth);
        }
    }
}

fn wait_with_timeout(mut child: Child, timeout: Duration) -> Result<Vec<u8>, String> {
    let mut stdout_pipe = child.stdout.take();
    let reader_handle = std::thread::spawn(move || {
        let mut buf = Vec::new();
        if let Some(ref mut out) = stdout_pipe {
            let _ = out.take((MAX_IMAGE_BYTES + 1024) as u64).read_to_end(&mut buf);
        }
        buf
    });

    let start = Instant::now();
    loop {
        match child.try_wait() {
            Ok(Some(status)) => {
                let bytes = reader_handle.join().unwrap_or_default();
                if status.success() {
                    return Ok(bytes);
                } else {
                    return Err(format!("command exited with {}", status));
                }
            }
            Ok(None) => {
                if start.elapsed() >= timeout {
                    let _ = child.kill();
                    let _ = child.wait();
                    let _ = reader_handle.join();
                    return Err("clipboard read timed out".to_string());
                }
                std::thread::sleep(Duration::from_millis(8));
            }
            Err(e) => return Err(format!("try_wait failed: {}", e)),
        }
    }
}

fn run_capture_cmd(program: &str, args: &[&str], timeout: Duration) -> Result<Vec<u8>, String> {
    let mut cmd = Command::new(program);
    cmd.args(args)
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::null());
    apply_xclip_env(&mut cmd, program);
    let child = cmd
        .spawn()
        .map_err(|e| format!("spawn {}: {}", program, e))?;
    wait_with_timeout(child, timeout)
}

fn read_targets() -> Vec<String> {
    let timeout = Duration::from_millis(1200);
    if has_wayland() {
        if let Ok(bytes) = run_capture_cmd("wl-paste", &["--list-types"], timeout) {
            let s = String::from_utf8_lossy(&bytes);
            let list: Vec<String> = s
                .lines()
                .map(|l| l.trim().to_string())
                .filter(|l| !l.is_empty())
                .collect();
            if !list.is_empty() {
                return list;
            }
        }
    }
    if has_x11() {
        if let Ok(bytes) = run_capture_cmd(
            "xclip",
            &["-o", "-selection", "clipboard", "-t", "TARGETS"],
            timeout,
        ) {
            let s = String::from_utf8_lossy(&bytes);
            return s
                .lines()
                .map(|l| l.trim().to_string())
                .filter(|l| !l.is_empty())
                .collect();
        }
    }
    Vec::new()
}

fn is_concealed(targets: &[String]) -> bool {
    targets.iter().any(|t| {
        let lower = t.to_ascii_lowercase();
        PRIVACY_TARGETS.iter().any(|p| lower == *p)
    })
}

fn has_target(targets: &[String], expected: &str) -> bool {
    targets
        .iter()
        .any(|t| t.eq_ignore_ascii_case(expected))
}

fn is_valid_clipboard_text(bytes: &[u8]) -> Option<String> {
    if bytes.is_empty() || bytes.contains(&0) || bytes.starts_with(b"\x89PNG\r\n\x1a\n") {
        return None;
    }
    let s = String::from_utf8(bytes.to_vec()).ok()?;
    if s.trim().is_empty() {
        return None;
    }
    Some(s)
}

fn read_text(targets: &[String]) -> Option<String> {
    let timeout = Duration::from_millis(1500);
    if has_wayland() {
        let mime = if has_target(targets, "text/plain;charset=utf-8") {
            Some("text/plain;charset=utf-8")
        } else if has_target(targets, "UTF8_STRING") {
            Some("UTF8_STRING")
        } else if has_target(targets, "text/plain") {
            Some("text/plain")
        } else {
            None
        };
        let args: Vec<&str> = match mime {
            Some(m) => vec!["--no-newline", "--type", m],
            None => vec!["--no-newline"],
        };
        if let Ok(bytes) = run_capture_cmd("wl-paste", &args, timeout) {
            if let Some(s) = is_valid_clipboard_text(&bytes) {
                return Some(s);
            }
        }
    }
    if has_x11() {
        for target in &["UTF8_STRING", "text/plain;charset=utf-8", "STRING"] {
            if let Ok(bytes) = run_capture_cmd(
                "xclip",
                &["-o", "-selection", "clipboard", "-t", target],
                timeout,
            ) {
                if let Some(s) = is_valid_clipboard_text(&bytes) {
                    return Some(s);
                }
            }
        }
    }
    None
}

fn read_png() -> Option<Vec<u8>> {
    let timeout = Duration::from_millis(2500);
    if has_wayland() {
        if let Ok(bytes) = run_capture_cmd("wl-paste", &["--type", "image/png"], timeout) {
            if parse_png_dimensions(&bytes).is_some() {
                return Some(bytes);
            }
        }
    }
    if has_x11() {
        if let Ok(bytes) = run_capture_cmd(
            "xclip",
            &["-o", "-selection", "clipboard", "-t", "image/png"],
            timeout,
        ) {
            if parse_png_dimensions(&bytes).is_some() {
                return Some(bytes);
            }
        }
    }
    None
}

/// Reads the current system clipboard (text or PNG image), respecting privacy hints.
pub fn capture_clipboard() -> Option<CapturedClipboard> {
    let targets = read_targets();
    if targets.is_empty() || is_concealed(&targets) {
        return None;
    }

    let offers_png = has_target(&targets, "image/png");
    let offers_text = has_target(&targets, "UTF8_STRING")
        || has_target(&targets, "text/plain;charset=utf-8")
        || has_target(&targets, "text/plain")
        || has_target(&targets, "STRING")
        || has_target(&targets, "TEXT");

    // Browser "Copy Image" typically offers `text/html` + `image/png` (no plain text).
    if offers_png && !offers_text {
        if let Some(png) = read_png() {
            return Some(CapturedClipboard::Image(png));
        }
    }

    if offers_text {
        if let Some(text) = read_text(&targets) {
            return Some(CapturedClipboard::Text(text));
        }
    }

    if offers_png {
        if let Some(png) = read_png() {
            return Some(CapturedClipboard::Image(png));
        }
    }

    None
}

pub fn hash_captured(cap: &CapturedClipboard) -> String {
    match cap {
        CapturedClipboard::Text(t) => compute_content_hash(EntryKind::Text, t.as_bytes()),
        CapturedClipboard::Image(b) => compute_content_hash(EntryKind::Image, b),
    }
}

fn pipe_to_background_setter(
    program: &str,
    args: &[&str],
    data: &[u8],
    timeout: Duration,
) -> Result<(), String> {
    let mut cmd = Command::new(program);
    cmd.args(args)
        .stdin(Stdio::piped())
        .stdout(Stdio::null())
        .stderr(Stdio::null());
    apply_xclip_env(&mut cmd, program);

    let mut child = cmd
        .spawn()
        .map_err(|e| format!("spawn {}: {}", program, e))?;

    if let Some(mut stdin) = child.stdin.take() {
        if let Err(e) = stdin.write_all(data) {
            drop(stdin);
            let _ = child.kill();
            let _ = child.wait();
            return Err(format!("write stdin {}: {}", program, e));
        }
    }

    let start = Instant::now();
    loop {
        match child.try_wait() {
            Ok(Some(status)) => {
                if status.success() {
                    return Ok(());
                } else {
                    return Err(format!("{} exited with {}", program, status));
                }
            }
            Ok(None) => {
                if start.elapsed() >= timeout {
                    let _ = child.kill();
                    let _ = child.wait();
                    return Err(format!("{} did not fork within timeout", program));
                }
                std::thread::sleep(Duration::from_millis(5));
            }
            Err(e) => {
                let _ = child.kill();
                let _ = child.wait();
                return Err(format!("wait {}: {}", program, e));
            }
        }
    }
}

fn write_runtime_paste_file(bytes: &[u8]) -> Result<PathBuf, String> {
    let path = env::var_os("XDG_RUNTIME_DIR")
        .filter(|v| !v.is_empty())
        .map(PathBuf::from)
        .map(|d| d.join("clipboard-lx-paste.bin"))
        .unwrap_or_else(|| PathBuf::from(format!("/tmp/clipboard-lx-paste-{}.bin", current_uid())));

    let mut file = OpenOptions::new()
        .create(true)
        .write(true)
        .truncate(true)
        .mode(0o600)
        .open(&path)
        .map_err(|e| format!("open {}: {}", path.display(), e))?;
    file.write_all(bytes)
        .map_err(|e| format!("write {}: {}", path.display(), e))?;
    file.flush()
        .map_err(|e| format!("flush {}: {}", path.display(), e))?;
    Ok(path)
}

fn try_shell_set_clipboard(method: &str, data: &[u8]) -> bool {
    let Ok(path) = write_runtime_paste_file(data) else {
        return false;
    };
    let escaped = path
        .to_string_lossy()
        .replace('\\', "\\\\")
        .replace('\'', "\\'");
    let gvariant_arg = format!("'{}'", escaped);

    let ok = Command::new("gdbus")
        .args([
            "call",
            "--session",
            "--timeout",
            "1",
            "--dest",
            "org.clipboardlx.Shell",
            "--object-path",
            "/org/clipboardlx/Shell",
            "--method",
            method,
            &gvariant_arg,
        ])
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .map(|s| s.success())
        .unwrap_or(false);

    let _ = fs::remove_file(&path);
    ok
}

/// Asks the GNOME Shell extension to inject a paste shortcut via `Clutter.VirtualInputDevice`.
pub fn try_shell_paste(delay_ms: u32) -> bool {
    let delay_arg = delay_ms.to_string();
    Command::new("gdbus")
        .args([
            "call",
            "--session",
            "--timeout",
            "2",
            "--dest",
            "org.clipboardlx.Shell",
            "--object-path",
            "/org/clipboardlx/Shell",
            "--method",
            "org.clipboardlx.Shell.Paste",
            &delay_arg,
        ])
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .map(|s| s.success())
        .unwrap_or(false)
}

fn write_via_backends(
    shell_method: &str,
    xclip_target: &str,
    wl_mime: &str,
    data: &[u8],
) -> Result<(), String> {
    if try_shell_set_clipboard(shell_method, data) {
        return Ok(());
    }

    let timeout = Duration::from_millis(2500);
    if has_x11()
        && pipe_to_background_setter(
            "xclip",
            &["-i", "-selection", "clipboard", "-t", xclip_target],
            data,
            timeout,
        )
        .is_ok()
    {
        return Ok(());
    }
    if has_wayland() {
        return pipe_to_background_setter("wl-copy", &["--type", wl_mime], data, timeout);
    }
    Err("Neither GNOME Shell, X11 (xclip), nor Wayland (wl-copy) clipboard available".to_string())
}

/// Writes raw UTF-8 text onto the system clipboard without requiring a stored entry.
pub fn write_text(text: &str) -> Result<(), String> {
    write_via_backends(
        "org.clipboardlx.Shell.SetTextFile",
        "UTF8_STRING",
        "text/plain",
        text.as_bytes(),
    )
}

/// Writes a stored entry (text or PNG image) onto the system clipboard.
pub fn write_clipboard(entry: &ClipboardEntry) -> Result<(), String> {
    match entry.kind {
        EntryKind::Text => write_text(&entry.text),
        EntryKind::Image => {
            let png = entry
                .image_png
                .as_deref()
                .ok_or_else(|| "Image entry missing PNG payload".to_string())?;
            write_via_backends(
                "org.clipboardlx.Shell.SetImageFile",
                "image/png",
                "image/png",
                png,
            )
        }
    }
}

#[cfg(test)]
mod tests {
    use super::newest_mutter_xauth;
    use std::fs;
    use std::thread;
    use std::time::{Duration, SystemTime, UNIX_EPOCH};

    #[test]
    fn newest_mutter_xauth_picks_latest_matching_file() {
        let nanos = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let dir = std::env::temp_dir().join(format!("clipd_xauth_test_{}", nanos));
        fs::create_dir_all(&dir).unwrap();

        let older = dir.join(".mutter-Xwaylandauth.AAAAAA");
        let newer = dir.join(".mutter-Xwaylandauth.BBBBBB");
        let unrelated = dir.join("other-file");

        fs::write(&older, b"old").unwrap();
        thread::sleep(Duration::from_millis(20));
        fs::write(&newer, b"new").unwrap();
        thread::sleep(Duration::from_millis(20));
        fs::write(&unrelated, b"ignore").unwrap();

        assert_eq!(newest_mutter_xauth(&dir), Some(newer));
        let _ = fs::remove_dir_all(&dir);
    }
}
